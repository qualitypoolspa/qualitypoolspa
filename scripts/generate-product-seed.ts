// Turns the bundled catalogue (src/data/products.ts and the supplier files)
// into supabase/seed.sql: the starting content for the admin panel.
//
//   npm run products:seed
//
// Run it after changing the bundled catalogue, then paste seed.sql into the
// Supabase SQL editor. The seed refuses to run on a table that already has
// products, so it can never overwrite the client's edits.
import { writeFileSync } from "node:fs";
import { bundledProducts } from "../src/data/products";
import { productToRow } from "../src/lib/product-row";

const rows = bundledProducts.map((p, i) => productToRow(p, (i + 1) * 10));
const json = JSON.stringify(rows, null, 1);
const Q = "$seed$";
if (json.includes(Q)) throw new Error(`The data contains the SQL quote marker ${Q}.`);

const sql = `-- Aquavia: starting catalogue (${rows.length} products). GENERATED by
-- scripts/generate-product-seed.ts from the bundled catalogue; don't edit by hand.
--
-- Run once, after migrations/0001_products.sql. It stops with an error if the
-- table already has products, so pasting it a second time can't overwrite
-- anything edited in /admin.

do $$
begin
  if exists (select 1 from public.products) then
    raise exception 'The products table already has content. Nothing was changed.';
  end if;
end $$;

insert into public.products
  (slug, category, collection, name, brand, tagline, description, seats, specs, images,
   is_visible, is_featured, is_selection, sort_order)
select
  slug, category, collection, name, brand, tagline, description, seats, specs, images,
  is_visible, is_featured, is_selection, sort_order
from jsonb_to_recordset(${Q}${json}${Q}::jsonb) as x(
  slug text, category text, collection text, name text, brand text, tagline text,
  description text, seats integer[], specs jsonb, images jsonb,
  is_visible boolean, is_featured boolean, is_selection boolean, sort_order integer
);

select count(*) as products_added from public.products;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${rows.length} products.`);
