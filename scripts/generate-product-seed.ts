// Turns the bundled catalogue (src/data/products.ts, the supplier files and the
// translations in src/i18n/product-text/) into two SQL files:
//
//   supabase/seed.sql                         the starting products, run once
//   supabase/migrations/0002_translations.sql Spanish and Swedish for a
//                                             database that's already in use
//
//   npm run products:seed
//
// Run it after changing the bundled catalogue or its translations, then paste
// the file you need into the Supabase SQL editor.
import { writeFileSync } from "node:fs";
import { bundledProducts } from "../src/data/products";
import { productLocales } from "../src/i18n/product-text";
import { productToRow, TRANSLATION_COLS } from "../src/lib/product-row";

const Q = "$data$";
const quote = (data: unknown) => {
  const json = JSON.stringify(data, null, 1);
  if (json.includes(Q)) throw new Error(`The data contains the SQL quote marker ${Q}.`);
  return `${Q}${json}${Q}`;
};

// ------------------------------------------------------------------ seed --

const rows = bundledProducts.map((p, i) => productToRow(p, (i + 1) * 10));
const cols = [
  "slug", "category", "collection", "name", "brand", "tagline", "description", ...TRANSLATION_COLS,
  "seats", "specs", "images", "is_visible", "is_featured", "is_selection", "sort_order",
];
const types: Record<string, string> = {
  seats: "integer[]", specs: "jsonb", images: "jsonb",
  is_visible: "boolean", is_featured: "boolean", is_selection: "boolean", sort_order: "integer",
};

const seed = `-- Aquavia: starting catalogue (${rows.length} products, English, Spanish and
-- Swedish). GENERATED by scripts/generate-product-seed.ts; don't edit by hand.
--
-- Run once, after migrations 0001 and 0002. It stops with an error if the
-- table already has products, so pasting it a second time can't overwrite
-- anything edited in /admin.

do $$
begin
  if exists (select 1 from public.products) then
    raise exception 'The products table already has content. Nothing was changed.';
  end if;
end $$;

insert into public.products
  (${cols.join(", ")})
select
  ${cols.join(", ")}
from jsonb_to_recordset(${quote(rows)}::jsonb) as x(
  ${cols.map((c) => `${c} ${types[c] ?? "text"}`).join(", ")}
);

select count(*) as products_added from public.products;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), seed);

// ------------------------------------------------------------- migration --
// Every English text in the catalogue with its translations, so products the
// client hasn't changed get translated, including spec rows on edited products.

const phrases = new Map<string, Record<string, string>>();
const add = (en: string, tr: Record<string, string | undefined>) => {
  const known = phrases.get(en) ?? {};
  for (const l of productLocales) if (tr[l] && tr[l] !== en) known[l] = tr[l]!;
  if (Object.keys(known).length) phrases.set(en, known);
};
for (const p of bundledProducts) {
  add(p.tagline.en, p.tagline);
  add(p.description.en, p.description);
  for (const s of p.specs ?? []) {
    if (s.group) add(s.group.en, s.group);
    add(s.label.en, s.label);
    add(s.value.en, s.value);
  }
}
// { es: { english: spanish, ... }, sv: { ... } }: a lookup the SQL reads by key.
const lookup: Record<string, Record<string, string>> = Object.fromEntries(productLocales.map((l) => [l, {}]));
for (const [en, tr] of phrases) for (const [l, text] of Object.entries(tr)) lookup[l][en] = text;
const pairCount = Object.values(lookup).reduce((n, m) => n + Object.keys(m).length, 0);

const setCols = productLocales.flatMap((l) =>
  (["tagline", "description"] as const).map(
    (c) => `  ${c}_${l} = coalesce(nullif(p.${c}_${l}, ''), m.tr->'${l}'->>p.${c})`,
  ),
);
const specKeys = productLocales.flatMap((l) =>
  (["group", "label", "value"] as const).map(
    (k) => `'${k}_${l}', coalesce(nullif(e->>'${k}_${l}', ''), m.tr->'${l}'->>(e->>'${k}'))`,
  ),
);

const migration = `-- Aquavia: Spanish and Swedish product texts. Schema AND data. GENERATED by
-- scripts/generate-product-seed.ts; don't edit by hand. Run after 0001.
-- Safe to re-run.
--
-- 1. Adds twin columns for the translated texts: tagline_es, description_es,
--    tagline_sv, description_sv. Spec rows (in the specs JSON) get
--    group_es / label_es / value_es keys and the same for _sv.
-- 2. Fills them in from the site's starting translations, matched on the
--    English text. A product whose English the client has rewritten keeps
--    blank translations (the site shows the English until they're written in
--    /admin), and nothing already translated is overwritten.

alter table public.products
${productLocales.flatMap((l) => [`  add column if not exists tagline_${l} text`, `  add column if not exists description_${l} text`]).join(",\n")};

-- One statement, with the translations inline: no temporary table, which the
-- Supabase SQL editor doesn't keep between statements.
with m as (select ${quote(lookup)}::jsonb as tr)
update public.products p set
${setCols.join(",\n")},
  specs = case when jsonb_array_length(p.specs) = 0 then p.specs else (
    select jsonb_agg(e || jsonb_strip_nulls(jsonb_build_object(
      ${specKeys.join(",\n      ")}
    )) order by i)
    from jsonb_array_elements(p.specs) with ordinality as s(e, i)
  ) end
from m;

select
  count(*) filter (where description_es is not null) as translated_es,
  count(*) filter (where description_sv is not null) as translated_sv,
  count(*) as products
from public.products;
`;
writeFileSync(new URL("../supabase/migrations/0002_translations.sql", import.meta.url), migration);

console.log(`Wrote supabase/seed.sql (${rows.length} products) and 0002_translations.sql (${pairCount} phrases).`);
