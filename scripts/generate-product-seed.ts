// Turns the bundled catalogue (src/data/products.ts, the supplier files and the
// translations in src/i18n/product-text/) into SQL files:
//
//   supabase/seed.sql                         the starting products, run once
//   supabase/migrations/0002_translations.sql   Spanish and Swedish, and
//   supabase/migrations/0003_more_languages.sql German, French and Russian,
//                                               for a database already in use
//
//   npm run products:seed
//
// Run it after changing the bundled catalogue or its translations, then paste
// the file you need into the Supabase SQL editor.
import { writeFileSync } from "node:fs";
import { bundledProducts } from "../src/data/products";
import { localeMigrations, productLocales, type ProductLocale } from "../src/i18n/product-locales";
import { productToRow, TRANSLATION_COLS } from "../src/lib/product-row";

const Q = "$data$";
const quote = (data: unknown) => {
  const json = JSON.stringify(data, null, 1);
  if (json.includes(Q)) throw new Error(`The data contains the SQL quote marker ${Q}.`);
  return `${Q}${json}${Q}`;
};

// ------------------------------------------------------------------ seed --

const rows = bundledProducts.map((p, i) => productToRow(p, (i + 1) * 10));
const cols = [
  "slug", "category", "collection", "name", "brand", "tagline", "description", ...TRANSLATION_COLS,
  "seats", "specs", "images", "is_visible", "is_featured", "is_selection", "sort_order",
];
const types: Record<string, string> = {
  seats: "integer[]", specs: "jsonb", images: "jsonb",
  is_visible: "boolean", is_featured: "boolean", is_selection: "boolean", sort_order: "integer",
};

const seed = `-- Aquavia: starting catalogue (${rows.length} products, English, Spanish and
-- Swedish). GENERATED by scripts/generate-product-seed.ts; don't edit by hand.
--
-- Run once, after migrations 0001, 0002 and 0003. It stops with an error if the
-- table already has products, so pasting it a second time can't overwrite
-- anything edited in /admin.

do $$
begin
  if exists (select 1 from public.products) then
    raise exception 'The products table already has content. Nothing was changed.';
  end if;
end $$;

insert into public.products
  (${cols.join(", ")})
select
  ${cols.join(", ")}
from jsonb_to_recordset(${quote(rows)}::jsonb) as x(
  ${cols.map((c) => `${c} ${types[c] ?? "text"}`).join(", ")}
);

select count(*) as products_added from public.products;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), seed);

// ------------------------------------------------------------- migration --
// Every English text in the catalogue with its translations, so products the
// client hasn't changed get translated, including spec rows on edited products.

const phrases = new Map<string, Record<string, string>>();
const add = (en: string, tr: Record<string, string | undefined>) => {
  const known = phrases.get(en) ?? {};
  for (const l of productLocales) if (tr[l] && tr[l] !== en) known[l] = tr[l]!;
  if (Object.keys(known).length) phrases.set(en, known);
};
for (const p of bundledProducts) {
  add(p.tagline.en, p.tagline);
  add(p.description.en, p.description);
  for (const s of p.specs ?? []) {
    if (s.group) add(s.group.en, s.group);
    add(s.label.en, s.label);
    add(s.value.en, s.value);
  }
}
// One migration per group of languages (localeMigrations): each adds its
// languages' columns and fills them, so a database that already ran the
// earlier ones only needs the new file.
const NAMES: Record<string, string> = { es: "Spanish", sv: "Swedish", de: "German", fr: "French", ru: "Russian" };
const listOf = (xs: string[]) => (xs.length > 1 ? `${xs.slice(0, -1).join(", ")} and ${xs.at(-1)}` : xs[0]);

function migrationSql(locales: readonly ProductLocale[], runAfter: string) {
  // { es: { english: spanish, ... }, sv: { ... } }: a lookup the SQL reads by key.
  const lookup: Record<string, Record<string, string>> = Object.fromEntries(locales.map((l) => [l, {}]));
  for (const [en, tr] of phrases) for (const [l, text] of Object.entries(tr)) if (l in lookup) lookup[l][en] = text;
  const count = Object.values(lookup).reduce((n, m) => n + Object.keys(m).length, 0);

  const setCols = locales.flatMap((l) =>
    (["tagline", "description"] as const).map(
      (c) => `  ${c}_${l} = coalesce(nullif(p.${c}_${l}, ''), m.tr->'${l}'->>p.${c})`,
    ),
  );
  const specKeys = locales.flatMap((l) =>
    (["group", "label", "value"] as const).map(
      (k) => `'${k}_${l}', coalesce(nullif(e->>'${k}_${l}', ''), m.tr->'${l}'->>(e->>'${k}'))`,
    ),
  );
  const colList = locales.flatMap((l) => [`tagline_${l}`, `description_${l}`]);
  const colLines = [colList.slice(0, 2).join(", ") + ",", ...(colList.length > 2 ? [colList.slice(2).join(", ") + "."] : [])];

  const sql = `-- Aquavia: ${listOf(locales.map((l) => NAMES[l]))} product texts. Schema AND data. GENERATED by
-- scripts/generate-product-seed.ts; don't edit by hand. Run after ${runAfter}.
-- Safe to re-run.
--
-- 1. Adds twin columns for the translated texts: ${colLines[0]}
--    ${colLines[1]} Spec rows (in the specs JSON) get
--    group_${locales[0]} / label_${locales[0]} / value_${locales[0]} keys and the same for ${listOf(locales.slice(1).map((l) => `_${l}`))}.
-- 2. Fills them in from the site's starting translations, matched on the
--    English text. A product whose English the client has rewritten keeps
--    blank translations (the site shows the English until they're written in
--    /admin), and nothing already translated is overwritten.

alter table public.products
${locales.flatMap((l) => [`  add column if not exists tagline_${l} text`, `  add column if not exists description_${l} text`]).join(",\n")};

-- One statement, with the translations inline: no temporary table, which the
-- Supabase SQL editor doesn't keep between statements.
with m as (select ${quote(lookup)}::jsonb as tr)
update public.products p set
${setCols.join(",\n")},
  specs = case when jsonb_array_length(p.specs) = 0 then p.specs else (
    select jsonb_agg(e || jsonb_strip_nulls(jsonb_build_object(
      ${specKeys.join(",\n      ")}
    )) order by i)
    from jsonb_array_elements(p.specs) with ordinality as s(e, i)
  ) end
from m;

select
${locales.map((l) => `  count(*) filter (where description_${l} is not null) as translated_${l},`).join("\n")}
  count(*) as products
from public.products;
`;
  return { sql, count };
}

const written: string[] = [];
localeMigrations.forEach((m, i) => {
  const { sql, count } = migrationSql(m.locales, i === 0 ? "0001" : localeMigrations[i - 1].file.slice(0, 4));
  writeFileSync(new URL(`../supabase/migrations/${m.file}`, import.meta.url), sql);
  written.push(`${m.file} (${count} phrases)`);
});

// ------------------------------------------------------------- additions --
// Products added to the bundled catalogue after the database was set up: an
// insert that skips any product already in the table (matched on category and
// slug), so it never touches what the client has edited. Safe to re-run.

const additions = [
  {
    file: "0004_harvia_saunas.sql",
    title: "Harvia sauna cabins",
    pick: (p: (typeof bundledProducts)[number]) => p.brand === "Harvia" && p.category === "saunas-hammam",
  },
];

for (const a of additions) {
  const list = bundledProducts.filter(a.pick);
  const addRows = list.map((p, i) => productToRow(p, (i + 1) * 10));
  const sql = `-- Aquavia: add the ${a.title} (${addRows.length} products) to a database that is
-- already in use. GENERATED by scripts/generate-product-seed.ts; don't edit by hand.
-- Run after 0003. Safe to re-run: products already in the table (same
-- category and address) are skipped, so nothing edited in /admin changes.
-- They are placed after the category's existing products, in catalogue order.

with base as (
  select coalesce(max(sort_order), 0) as top
  from public.products
  where category = ${`'${list[0]?.category ?? ""}'`}
)
insert into public.products
  (${cols.join(", ")})
select
  ${cols.filter((c) => c !== "sort_order").join(", ")}, base.top + x.sort_order
from base, jsonb_to_recordset(${quote(addRows)}::jsonb) as x(
  ${cols.map((c) => `${c} ${types[c] ?? "text"}`).join(", ")}
)
on conflict (category, slug) do nothing;

select count(*) as ${a.file.slice(5, -4)}_in_table
from public.products
where brand = ${`'${list[0]?.brand ?? ""}'`} and category = ${`'${list[0]?.category ?? ""}'`};
`;
  writeFileSync(new URL(`../supabase/migrations/${a.file}`, import.meta.url), sql);
  written.push(`${a.file} (${addRows.length} products)`);
}

console.log(`Wrote supabase/seed.sql (${rows.length} products), ${written.join(", ")}.`);
